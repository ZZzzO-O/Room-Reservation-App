def save_user(conn: DatabaseConnection, user: User) -> None:
    """
    Insert or update a user record in SQLite.

    Args:
        conn: Database connection.
        user (User): User profile to persist.

    Returns:
        None
    """
    with conn:
        conn.execute(
            """
            INSERT INTO users
            (user_id, email, password_hash, salt, role, name)
            VALUES (?, ?, ?, ?, ?, ?)
            ON CONFLICT(user_id) DO UPDATE SET
                email = excluded.email,
                password_hash = excluded.password_hash,
                salt = excluded.salt,
                role = excluded.role,
                name = excluded.name;
            """,
            (
                user.user_id,
                user.email,
                user.password_hash,
                user.salt,
                user.role,
                user.name,
            ),
        )


def load_users(conn: DatabaseConnection) -> Dict[str, User]:
    """
    Load all registered user accounts from SQLite keyed by email.

    Args:
        conn (sqlite3.Connection): Database connection.

    Returns:
        Dict[str, User]: Dictionary of User instances keyed by email.
    """
    users: Dict[str, User] = {}
    rows = conn.execute(
        "SELECT user_id, email, password_hash, salt, role, name FROM users;"
    ).fetchall()
    for row in rows:
        user = User(
            user_id=row["user_id"],
            email=row["email"],
            password_hash=row["password_hash"],
            salt=row["salt"],
            role=row["role"],
            name=row["name"],
        )
        users[user.email] = user
    return users


def save_session(conn: DatabaseConnection, session: Session) -> None:
    """
    Save an active authentication session to SQLite.

    Args:
        conn: Database connection.
        session (Session): Active session to persist.

    Returns:
        None
    """
    with conn:
        conn.execute(
            """
            INSERT INTO sessions (token, user_id, expires_at, created_at)
            VALUES (?, ?, ?, ?)
            ON CONFLICT(token) DO UPDATE SET
                expires_at = excluded.expires_at;
            """,
            (
                session.token,
                session.user_id,
                session.expires_at.isoformat(),
                session.created_at.isoformat(),
            ),
        )


def delete_session(conn: DatabaseConnection, token: str) -> None:
    """
    Remove an authenticated session from SQLite upon logout.

    Args:
        conn (sqlite3.Connection): Database connection.
        token (str): Session token to delete.

    Returns:
        None
    """
    with conn:
        conn.execute("DELETE FROM sessions WHERE token = ?;", (token,))


def load_sessions(conn: DatabaseConnection) -> Dict[str, Session]:
    """
    Load non-expired sessions from SQLite into memory.

    Args:
        conn (sqlite3.Connection): Database connection.

    Returns:
        Dict[str, Session]: Dictionary of active sessions keyed by token.
    """
    sessions: Dict[str, Session] = {}
    now_iso = datetime.utcnow().isoformat()
    # Clean up expired sessions automatically
    with conn:
        conn.execute("DELETE FROM sessions WHERE expires_at < ?;", (now_iso,))

    rows = conn.execute(
        "SELECT token, user_id, expires_at, created_at FROM sessions;"
    ).fetchall()
    for row in rows:
        session = Session(
            token=row["token"],
            user_id=row["user_id"],
            expires_at=datetime.fromisoformat(row["expires_at"]),
            created_at=datetime.fromisoformat(row["created_at"]),
        )
        sessions[session.token] = session
    return sessions


