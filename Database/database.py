DEFAULT_DB_FILE = "app.db"
POSTGRES_SCHEMES = ("postgres://", "postgresql://")


class DatabaseConnection(Protocol):
    """Common operations used by both supported database drivers."""

    def execute(
        self, query: str, parameters: Sequence[object] = ()
    ) -> Any: ...

    def __enter__(self) -> "DatabaseConnection": ...

    def __exit__(
        self, exc_type: Any, exc_value: Any, traceback: Any
    ) -> bool | None: ...

    def close(self) -> None: ...


class PostgresConnection:
    """Adapt psycopg's connection to the SQLite-style SQL used by this app."""

    def __init__(self, connection: Any) -> None:
        self._connection = connection

    def execute(
        self, query: str, parameters: Sequence[object] = ()
    ) -> Any:
        return self._connection.execute(query.replace("?", "%s"), parameters)

    def __enter__(self):
        self._connection.__enter__()
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        return self._connection.__exit__(exc_type, exc_value, traceback)

    def close(self) -> None:
        self._connection.close()


def get_connection(db_path: str = DEFAULT_DB_FILE) -> DatabaseConnection:
    """
    Open a database connection, selecting PostgreSQL for a connection URL.

    Args:
        db_path (str): SQLite path, ':memory:', or PostgreSQL connection URL.

    Returns:
        A configured SQLite or PostgreSQL connection.
    """
    if db_path.startswith(POSTGRES_SCHEMES):
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:
            raise RuntimeError(
                "PostgreSQL support requires psycopg; install "
                "requirements-render.txt."
            ) from exc
        return PostgresConnection(
            psycopg.connect(db_path, row_factory=dict_row)
        )

    conn = sqlite3.connect(db_path, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON;")
    return conn


def init_db(conn: DatabaseConnection) -> None:
    """
    Create database tables for rooms, closures, users, and sessions.

    Args:
        conn: Database connection.

    Returns:
        None
    """
    is_sqlite = isinstance(conn, sqlite3.Connection)
    period_id = (
        "INTEGER PRIMARY KEY AUTOINCREMENT"
        if is_sqlite
        else "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    )
    schemas = (
        """
        CREATE TABLE IF NOT EXISTS rooms (
            room_id TEXT PRIMARY KEY,
            name TEXT NOT NULL DEFAULT '',
            capacity INTEGER NOT NULL,
            equipment_json TEXT NOT NULL DEFAULT '{}'
        );
        """,
        f"""
        CREATE TABLE IF NOT EXISTS unavailable_periods (
            id {period_id},
            room_id TEXT NOT NULL,
            start_date TEXT NOT NULL,
            end_date TEXT NOT NULL,
            reason TEXT NOT NULL DEFAULT '',
            FOREIGN KEY (room_id) REFERENCES rooms(room_id)
                ON DELETE CASCADE
        );
        """,
        """
        CREATE TABLE IF NOT EXISTS users (
            user_id TEXT PRIMARY KEY,
            email TEXT UNIQUE NOT NULL,
            password_hash TEXT NOT NULL,
            salt TEXT NOT NULL,
            role TEXT NOT NULL,
            name TEXT NOT NULL DEFAULT ''
        );
        """,
        """
        CREATE TABLE IF NOT EXISTS sessions (
            token TEXT PRIMARY KEY,
            user_id TEXT NOT NULL,
            expires_at TEXT NOT NULL,
            created_at TEXT NOT NULL,
            FOREIGN KEY (user_id) REFERENCES users(user_id)
                ON DELETE CASCADE
        );
        """,
        """
        CREATE TABLE IF NOT EXISTS reservations (
            reservation_id TEXT PRIMARY KEY,
            competency TEXT NOT NULL,
            room_id TEXT NOT NULL,
            group_size INTEGER NOT NULL,
            start_date TEXT NOT NULL,
            end_date TEXT,
            start_time TEXT NOT NULL,
            end_time TEXT NOT NULL,
            repetition TEXT NOT NULL,
            FOREIGN KEY (room_id) REFERENCES rooms(room_id)
                ON DELETE CASCADE
        );
        """,
    )
    with conn:
        for schema in schemas:
            conn.execute(schema)


# Room Persistence Functions
def save_room(conn: DatabaseConnection, room: Room) -> None:
    """
    Insert or update a room record in SQLite.

    Args:
        conn: Database connection.
        room (Room): Room instance to persist.

    Returns:
        None
    """
    eq_json = json.dumps(room.equipment)
    with conn:
        conn.execute(
            """
            INSERT INTO rooms (room_id, name, capacity, equipment_json)
            VALUES (?, ?, ?, ?)
            ON CONFLICT(room_id) DO UPDATE SET
                name = excluded.name,
                capacity = excluded.capacity,
                equipment_json = excluded.equipment_json;
            """,
            (room.room_id, room.name, room.capacity, eq_json),
        )


def delete_room(conn: DatabaseConnection, room_id: str) -> None:
    """
    Delete a room record and its closure periods from SQLite.

    Args:
        conn: Database connection.
        room_id (str): Identifier of the room to delete.

    Returns:
        None
    """
    with conn:
        conn.execute("DELETE FROM rooms WHERE room_id = ?;", (room_id,))


def save_unavailable_period(
    conn: DatabaseConnection, room_id: str, period: UnavailablePeriod
) -> None:
    """
    Save an unavailable period associated with a room.

    Args:
        conn: Database connection.
        room_id (str): Associated room ID.
        period (UnavailablePeriod): Period to save.

    Returns:
        None
    """
    with conn:
        query = """
            INSERT INTO unavailable_periods
            (room_id, start_date, end_date, reason)
            VALUES (?, ?, ?, ?)
        """
        parameters = (
            room_id,
            period.start_date.isoformat(),
            period.end_date.isoformat(),
            period.reason,
        )
        if isinstance(conn, sqlite3.Connection):
            cursor = conn.execute(query, parameters)
            period.period_id = cursor.lastrowid
        else:
            cursor = conn.execute(f"{query} RETURNING id", parameters)
            period.period_id = cursor.fetchone()["id"]


def update_unavailable_period(
    conn: DatabaseConnection, room_id: str, period: UnavailablePeriod
) -> None:
    """Persist changes to an existing unavailable period."""
    with conn:
        cursor = conn.execute(
            """
            UPDATE unavailable_periods
            SET start_date = ?, end_date = ?, reason = ?
            WHERE room_id = ? AND id = ?;
            """,
            (
                period.start_date.isoformat(),
                period.end_date.isoformat(),
                period.reason,
                room_id,
                period.period_id,
            ),
        )
        if cursor.rowcount != 1:
            raise ValueError(
                f"Unavailable period {period.period_id} does not exist "
                f"for room {room_id}."
            )


def delete_unavailable_period(
    conn: DatabaseConnection, room_id: str, period_id: int
) -> None:
    """Delete an unavailable period from SQLite."""
    with conn:
        cursor = conn.execute(
            "DELETE FROM unavailable_periods WHERE room_id = ? AND id = ?;",
            (room_id, period_id),
        )
        if cursor.rowcount != 1:
            raise ValueError(
                f"Unavailable period {period_id} does not exist "
                f"for room {room_id}."
            )


def load_rooms(conn: DatabaseConnection) -> Dict[str, Room]:
    """
    Load all rooms and their unavailable periods from SQLite into memory.

    Args:
        conn: Database connection.

    Returns:
        Dict[str, Room]: Dictionary of Room instances keyed by room_id.
    """
    rooms: Dict[str, Room] = {}
    rows = conn.execute(
        "SELECT room_id, name, capacity, equipment_json FROM rooms;"
    ).fetchall()
    for row in rows:
        equipment = json.loads(row["equipment_json"])
        room = Room(
            room_id=row["room_id"],
            name=row["name"],
            capacity=row["capacity"],
            equipment=equipment,
        )
        rooms[room.room_id] = room

    period_rows = conn.execute(
        """
        SELECT id, room_id, start_date, end_date, reason
        FROM unavailable_periods;
        """
    ).fetchall()
    for prow in period_rows:
        rid = prow["room_id"]
        if rid in rooms:
            p = UnavailablePeriod(
                start_date=date.fromisoformat(prow["start_date"]),
                end_date=date.fromisoformat(prow["end_date"]),
                reason=prow["reason"],
                period_id=prow["id"],
            )
            rooms[rid].unavailable_periods.append(p)

    return rooms


